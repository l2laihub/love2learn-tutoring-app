#!/usr/bin/env node
/**
 * Bundle the legal docs into the app.
 *
 * docs/PRIVACY_POLICY.md and docs/TERMS_OF_SERVICE.md stay the source of
 * truth. This writes src/content/legal.ts so the /privacy and /terms screens
 * (and therefore https://dalesson.app/privacy and /terms on the web build)
 * always show the same text. Re-run after editing either doc:
 *
 *   npm run legal
 */
/* global __dirname */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, 'docs', f), 'utf8').replace(/\r\n/g, '\n').trim();

const out = `// AUTO-GENERATED by scripts/build-legal-content.js from docs/*.md.
// Do not edit by hand: edit the markdown and run \`npm run legal\`.

export const PRIVACY_POLICY_MD = ${JSON.stringify(read('PRIVACY_POLICY.md'))};

export const TERMS_OF_SERVICE_MD = ${JSON.stringify(read('TERMS_OF_SERVICE.md'))};
`;

fs.mkdirSync(path.join(root, 'src/content'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/content/legal.ts'), out);
console.log('Wrote src/content/legal.ts');
